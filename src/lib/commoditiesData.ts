// Generate realistic historical daily price bars
function generateHistory(basePrice: number, volatility: number, drift: number, count = 90): PricePoint[] {
  const points: PricePoint[] = [];
  let price = basePrice * 0.92;
  const now = Date.now();
  const dayMs = 24 * 60 * 60 * 1000;

  for (let i = count; i >= 0; i--) {
    const timestamp = now - i * dayMs;
    const date = new Date(timestamp).toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    
    // Brownian motion with mean drift
    const randomShock = (Math.random() - 0.485) * 2 * volatility;
    price = Math.max(price * (1 + drift + randomShock), basePrice * 0.4);
    
    const dayVar = price * (volatility * 0.7);
    const open = Number((price - (Math.random() - 0.5) * dayVar).toFixed(2));
    const close = Number(price.toFixed(2));
    const high = Number((Math.max(open, close) + Math.random() * dayVar).toFixed(2));
    const low = Number((Math.min(open, close) - Math.random() * dayVar).toFixed(2));
    const volume = Math.floor(10000 + Math.random() * 90000);

    points.push({
      date,
      timestamp,
      open,
      high,
      low,
      close,
      volume,
    });
  }

  // Ensure current close matches basePrice roughly
  if (points.length > 0) {
    points[points.length - 1].close = basePrice;
    points[points.length - 1].high = Math.max(points[points.length - 1].high, basePrice);
    points[points.length - 1].low = Math.min(points[points.length - 1].low, basePrice);
  }

  return points;
}

